/**
 * Get translation dictionary for language code with fallback to 'en'
 */
export function getI18nText(langCode = 'en'): Record<string, string> {
  return TRANSLATIONS[langCode] || TRANSLATIONS['en'];
}

/**
 * Detect default language based on browser/location context
 */
export function detectDefaultLanguage(): string {
  try {
    const navLang = navigator.language || (navigator.languages && navigator.languages[0]);
    if (navLang) {
      const langPrefix = navLang.toLowerCase().slice(0, 2);
      if (SUPPORTED_LANGUAGES.some(l => l.code === langPrefix)) {
        return langPrefix;
      }
    }
  } catch (e) {
    // fallback
  }
  return 'en';
}
